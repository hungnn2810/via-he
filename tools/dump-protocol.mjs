// Dumps the client/server message protocol as Markdown, from the server as the source of truth.
// Server handlers are registered as this.handle('name', (pr, c, m: { ... }) => ...) or
// this.onMessage('name', ...); the inline TypeScript type gives the exact payload keys.
// Run: node tools/dump-protocol.mjs > docs/client/protocol.md
import { readFileSync } from 'node:fs';

const room = readFileSync('server/src/rooms/StreetRoom.ts', 'utf8');
const index = readFileSync('server/src/index.ts', 'utf8');

const accepts = [];
const pattern = /this\.(handle|onMessage)(?:<[^>]*>)?\(\s*'([^']+)'\s*,?([^\n]*)/g;
for (const m of pattern.exec === undefined ? [] : room.matchAll(pattern)) {
  const [, kind, name, tail] = m;
  const type = tail.match(/m:\s*(\{[^}]*\}|Partial<[^>]+>|[A-Za-z]+)/);
  const keys = type
    ? type[1]
        .replace(/^\{|\}$/g, '')
        .split(';')
        .map((s) => s.trim().split(':')[0].trim())
        .filter(Boolean)
        .join(', ')
    : '';
  const line = room.slice(0, m.index).split('\n').length;
  accepts.push({ name, kind, keys: keys || '—', line });
}

const pushes = [...new Set([...room.matchAll(/(?:broadcast|send)\(\s*'([^']+)'/g)].map((m) => m[1]))];
const routes = [...index.matchAll(/app\.(get|post)\(\s*'([^']+)'/g)].map((m) => `${m[1].toUpperCase()} ${m[2]}`);

const rows = accepts.sort((a, b) => a.name.localeCompare(b.name));
console.log('# Message protocol\n');
console.log('Generated by `node tools/dump-protocol.mjs`. The server is the source of truth.\n');
console.log(`Server accepts ${rows.length} messages, pushes ${pushes.length}, exposes ${routes.length} HTTP routes.\n`);
console.log('## Client to server\n');
console.log('| Message | Payload keys | Registered |');
console.log('| --- | --- | --- |');
for (const r of rows) console.log(`| \`${r.name}\` | ${r.keys} | \`StreetRoom.ts:${r.line}\` (${r.kind}) |`);
console.log('\n## Server to client\n');
for (const p of pushes.sort()) console.log(`- \`${p}\``);
console.log('\n## HTTP\n');
for (const r of routes) console.log(`- \`${r}\``);
